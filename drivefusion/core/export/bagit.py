"""BagIt packaging (RFC 8493), and an honest account of what is in the bag.

A bag is a directory with its payload under ``data/``, a manifest of checksums
over that payload, and tag files describing the bag itself. The format's value
is that a bag can be verified years later by a program that knows nothing about
what made it.

**The payload is the description, not the archive.** This matters enough to say
in the bag itself, not only here. Drive Fusion never copies user data, so
``data/`` holds the documents it generated — the metadata, the manifests, the
scorecards, the plan — and the manifest checksums cover exactly those. A bag
whose manifest listed the user's files without containing them would verify as
incomplete everywhere it was taken, and a bag that claimed to *be* the archive
would be a straightforward lie. The content inventory inside the payload
carries the archive's own checksums, which is the right place for them: they
describe something the bag points at rather than something it holds.

So: ``Bag-Size`` and ``Payload-Oxum`` are the size of the description.
``External-Description`` says what is being described and that the files are
elsewhere. Anyone verifying this bag is verifying that the description arrived
intact, which is a genuinely useful thing to be able to check.
"""

from __future__ import annotations

import hashlib
from pathlib import Path

from drivefusion.core.export import writer

BAGIT_VERSION = "1.0"
TAG_FILE_CHARACTER_ENCODING = "UTF-8"

#: Where payload files live in a bag. Anything written outside this (and outside
#: the tag files below) would make the bag invalid.
PAYLOAD_DIR = "data"

HASH_ALGORITHM = "sha256"
MANIFEST = f"manifest-{HASH_ALGORITHM}.txt"
TAG_MANIFEST = f"tagmanifest-{HASH_ALGORITHM}.txt"

#: Tag files the manifest of tag files covers. ``bagit.txt`` is included
#: because RFC 8493 recommends it, and omitting it is a common way bags fail a
#: strict validator.
TAG_FILES = ("bagit.txt", "bag-info.txt", MANIFEST)


def payload_path(relative: str | Path) -> str:
    """Where a generated document goes inside the bag."""
    return f"{PAYLOAD_DIR}/{Path(relative).as_posix()}"


def _digest(path: Path) -> str:
    digest = hashlib.new(HASH_ALGORITHM)
    with open(path, "rb") as handle:
        while chunk := handle.read(1 << 20):
            digest.update(chunk)
    return digest.hexdigest()


def _payload_files(root: Path) -> list[Path]:
    payload = root / PAYLOAD_DIR
    if not payload.is_dir():
        return []
    return sorted(path for path in payload.rglob("*") if path.is_file())


def payload_oxum(root: Path) -> str:
    """``octetcount.filecount`` over the payload, as RFC 8493 defines it."""
    files = _payload_files(root)
    octets = sum(path.stat().st_size for path in files)
    return f"{octets}.{len(files)}"


def finalise(
    root: Path,
    *,
    version: str,
    described: dict,
    source_organization: str | None = None,
) -> dict:
    """Write the manifest and tag files over a bundle whose payload is complete.

    Called last, because a manifest is a statement about files that already
    exist. Returns a small summary for the caller to report.

    The order is fixed by the format: the payload manifest must exist before
    the tag manifest, which covers it.
    """
    files = _payload_files(root)
    if not files:
        raise writer.ExportError(
            "the bag has no payload: nothing was written under "
            f"{PAYLOAD_DIR}/ before finalise()"
        )

    lines = []
    for path in files:
        relative = path.relative_to(root).as_posix()
        lines.append(f"{_digest(path)}  {relative}")
    writer.write_lines(root, MANIFEST, lines)

    writer.write_lines(
        root,
        "bagit.txt",
        [
            f"BagIt-Version: {BAGIT_VERSION}",
            f"Tag-File-Character-Encoding: {TAG_FILE_CHARACTER_ENCODING}",
        ],
    )

    oxum = payload_oxum(root)
    info = [
        f"Source-Organization: {source_organization or 'not stated'}",
        f"Bagging-Date: {described.get('generated_at', '')[:10]}",
        f"Bag-Software-Agent: Drive Fusion {version}",
        f"Payload-Oxum: {oxum}",
        # The line that stops this bag being mistaken for a bag of the archive.
        "External-Description: Description of a local storage archive "
        "generated by Drive Fusion. The payload is the description — metadata, "
        "manifests, scorecards and plans. The described files are NOT in this "
        f"bag; they remain on {described.get('volumes', 0)} volume(s) across "
        f"{described.get('drives', 0)} drive(s) and were not modified, moved or "
        "copied in order to produce it. Their own checksums are inside the "
        "payload, in the content inventory.",
        f"External-Identifier: {described.get('catalog_id', 'unknown')}",
        f"Internal-Sender-Description: {described.get('files', 0)} files, "
        f"{described.get('bytes', 0)} bytes catalogued; "
        f"{described.get('collections', 0)} confirmed collection(s)",
    ]
    writer.write_lines(root, "bag-info.txt", info)

    tag_lines = []
    for name in TAG_FILES:
        path = root / name
        if path.is_file():
            tag_lines.append(f"{_digest(path)}  {name}")
    writer.write_lines(root, TAG_MANIFEST, tag_lines)

    return {
        "payload_files": len(files),
        "payload_oxum": oxum,
        "algorithm": HASH_ALGORITHM,
        "manifest": MANIFEST,
    }


def validate(root: Path) -> list[str]:
    """Check a bag the way a reader would. Returns problems, empty if valid.

    Here because a format implemented without a reader is a format nobody has
    checked. This validates the bags this module writes, in the tests, every
    run — the alternative is discovering in a year that the manifests never
    matched.
    """
    problems: list[str] = []
    root = Path(root)

    declaration = root / "bagit.txt"
    if not declaration.is_file():
        problems.append("bagit.txt is missing")
    else:
        text = declaration.read_text(encoding="utf-8")
        if "BagIt-Version:" not in text:
            problems.append("bagit.txt has no BagIt-Version")

    manifest = root / MANIFEST
    if not manifest.is_file():
        problems.append(f"{MANIFEST} is missing")
        return problems

    listed: dict[str, str] = {}
    for line in manifest.read_text(encoding="utf-8").splitlines():
        if not line.strip():
            continue
        checksum, _, relative = line.partition("  ")
        if not relative:
            problems.append(f"malformed manifest line: {line!r}")
            continue
        listed[relative] = checksum

    for relative, expected in listed.items():
        path = root / relative
        if not path.is_file():
            problems.append(f"{relative} is in the manifest but not in the bag")
            continue
        actual = _digest(path)
        if actual != expected:
            problems.append(
                f"{relative} does not match its manifest checksum "
                f"(expected {expected[:12]}…, got {actual[:12]}…)"
            )

    for path in _payload_files(root):
        relative = path.relative_to(root).as_posix()
        if relative not in listed:
            problems.append(f"{relative} is in the payload but not in the manifest")

    info = root / "bag-info.txt"
    if info.is_file():
        for line in info.read_text(encoding="utf-8").splitlines():
            if line.startswith("Payload-Oxum:"):
                stated = line.split(":", 1)[1].strip()
                actual = payload_oxum(root)
                if stated != actual:
                    problems.append(
                        f"Payload-Oxum says {stated} but the payload is {actual}"
                    )

    tag_manifest = root / TAG_MANIFEST
    if not tag_manifest.is_file():
        problems.append(f"{TAG_MANIFEST} is missing")
    else:
        for line in tag_manifest.read_text(encoding="utf-8").splitlines():
            if not line.strip():
                continue
            checksum, _, relative = line.partition("  ")
            path = root / relative
            if not path.is_file():
                problems.append(f"{relative} is in the tag manifest but absent")
            elif _digest(path) != checksum:
                problems.append(f"{relative} does not match its tag checksum")

    return problems
