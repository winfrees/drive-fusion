"""The only writer of user-facing files, and the only place that may create one.

Every write in this package goes through :func:`write`. It asserts three things
before a byte is written:

* the target resolves **inside** the export root the user chose,
* the target does **not already exist**, and
* the root is not inside a catalogued scope root.

The first two are what make an export incapable of damaging anything: a path
that cannot escape the root cannot reach the archive, and a file that must not
exist cannot overwrite a previous export. The third is belt and braces against
the one plausible way a user could aim this at their own data — choosing their
media drive as the export destination — which would have the tool writing into
the tree it promises never to modify.

**There is no delete function here, and no overwrite path.** Not "none is
exposed": none exists. An export that would collide fails, and the failure names
the colliding path. Exports land in a new timestamped directory each time, so a
collision means a genuine bug rather than an ordinary second run.

`shutil.copy*` is deliberately absent too. This package writes documents it
generated; it never moves user data, so it never opens a source file for any
purpose. Copying is something the user does, with their own tools, from a
checklist.
"""

from __future__ import annotations

import os
from datetime import datetime, timezone
from pathlib import Path

#: Written at the top of every bundle. The disclaimer §1 requires in every
#: export, and the sentence that stops a bundle being mistaken for evidence of
#: compliance with a policy nobody has adopted here.
DISCLAIMER = """\
This bundle was generated by Drive Fusion, a read-only cataloging and
consolidation-planning tool.

* Nothing in the archive it describes was modified, moved, renamed or deleted
  in order to produce this bundle. Drive Fusion has no code that can do any of
  those things.
* The plans and checklists here are documents. There is no executor: every
  step is something a person does, with their own tools.
* This is not a compliance artifact, and not a Data Management and Sharing Plan.
  It does not certify conformance with any policy. It records what was found and
  what the tool's own rubrics make of it, with the version of each rubric named
  so the judgement can be checked.
* Drive Fusion is not for identifiable human-subjects data, PHI, or otherwise
  regulated data, and must not be used to describe any.
"""


class ExportError(Exception):
    """A write was refused, or the export root is not usable."""


def timestamped_root(base: str | Path, *, label: str = "export") -> Path:
    """A new directory under *base*, named for the moment it was made.

    Never an existing directory: §3.1 says every export lands in a new folder
    and that existing exports are never overwritten or removed, and the only
    way to guarantee that is to refuse to reuse one. A second export within the
    same second gets a suffix rather than joining the first.
    """
    base_path = Path(base).expanduser().resolve()
    stamp = datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%SZ")

    candidate = base_path / f"{label}-{stamp}"
    suffix = 1
    while candidate.exists():
        suffix += 1
        candidate = base_path / f"{label}-{stamp}-{suffix}"
        if suffix > 1000:
            raise ExportError(
                f"cannot find an unused export directory under {base_path}"
            )
    return candidate


def prepare_root(base: str | Path, *, label: str = "export", catalog=None) -> Path:
    """Create and return a fresh export root, checking it is a safe place to write.

    The catalog is consulted, when given, so an export cannot be aimed at a
    scanned tree. That is the only realistic way this tool could write into
    user media, and a path check is the only thing standing in the way: the
    user picks the destination, and "my archive drive" is a tempting answer.
    """
    root = timestamped_root(base, label=label)

    if catalog is not None:
        # Reported against the folder the user actually named, not the
        # timestamped one inside it: the subfolder does not exist yet, and
        # naming it in the error makes the message read like a bug report.
        _refuse_scanned_locations(root, catalog, named=Path(base).expanduser())

    try:
        root.mkdir(parents=True, exist_ok=False)
    except OSError as error:
        raise ExportError(f"cannot create the export directory {root}: {error}")
    return root


def _refuse_scanned_locations(root: Path, catalog, named: Path | None = None) -> None:
    """Refuse an export root that sits inside a catalogued scope root.

    Only that direction is checked, and only that direction matters. A bundle
    beside the archive — ``D:\\exports`` next to ``D:\\Research`` — touches
    nothing in it and is a perfectly reasonable choice. The opposite check, for
    a scanned tree inside the bundle, was written and then removed: the bundle
    is always a new empty directory, so nothing can be inside it, and a rule
    that cannot fire reads as protection that is not there.
    """
    try:
        rows = catalog.conn.execute("SELECT path FROM scope_root").fetchall()
    except Exception:            # noqa: BLE001 - a catalog without the table
        return

    for row in rows:
        scanned = row["path"] if not isinstance(row, (tuple, list)) else row[0]
        if not scanned:
            continue
        try:
            scanned_path = Path(scanned).expanduser().resolve()
        except OSError:
            continue

        if _within(root, scanned_path):
            raise ExportError(
                f"refusing to export into {named or root}: it is inside the "
                f"scanned tree {scanned_path}. Drive Fusion does not write to "
                "the media it catalogues — choose a destination outside your "
                "archive."
            )


def _within(inner: Path, outer: Path) -> bool:
    """Whether *inner* is *outer* or sits beneath it.

    Compared on resolved paths, part by part, rather than on strings: a string
    prefix test makes ``/data/archive-old`` look like it is inside
    ``/data/archive``.
    """
    try:
        inner_parts = inner.resolve().parts
        outer_parts = outer.resolve().parts
    except OSError:
        return False
    return inner_parts[: len(outer_parts)] == outer_parts


def resolve(root: Path, relative: str | Path) -> Path:
    """The absolute path for *relative* inside *root*, or raise.

    Resolved before the containment check, so ``../`` and a symlinked component
    are both caught. An absolute *relative* is refused outright rather than
    silently reinterpreted.
    """
    candidate = Path(relative)
    if candidate.is_absolute():
        raise ExportError(
            f"{relative!r} is an absolute path; everything in a bundle is "
            "named relative to its root"
        )
    if ".." in candidate.parts:
        raise ExportError(
            f"{relative!r} climbs out of the bundle; a bundle has no parent"
        )

    root_resolved = Path(root).resolve()
    target = (root_resolved / candidate).resolve()

    if not _within(target, root_resolved):
        raise ExportError(
            f"{relative!r} resolves to {target}, outside the export root "
            f"{root_resolved}. Nothing is written outside the folder you chose."
        )
    return target


def write(root: Path, relative: str | Path, content: str | bytes) -> Path:
    """Write one file inside the bundle. The only way this package creates files.

    Refuses a target that already exists. There is no ``overwrite`` parameter,
    because there is no case for one: bundles are new directories, so a
    collision is a bug in the code that composed the bundle, and silently
    replacing a file would hide it.
    """
    from drivefusion.core import wording

    target = resolve(root, relative)

    if target.exists():
        raise ExportError(
            f"{target} already exists. Drive Fusion never overwrites a file; "
            "every export goes into a new directory."
        )

    if isinstance(content, str):
        # Read before it is written. The denylist is cheap and the alternative
        # is a document that tells someone to delete their data (§3.2).
        wording.assert_safe(content, what=f"export file {Path(relative).name}")
        payload = content.encode("utf-8")
    else:
        payload = content

    target.parent.mkdir(parents=True, exist_ok=True)

    # "xb" rather than "wb": the mode itself refuses to truncate an existing
    # file, so the check above cannot be defeated by a race.
    with open(target, "xb") as handle:
        handle.write(payload)
        handle.flush()
        os.fsync(handle.fileno())
    return target


def write_lines(root: Path, relative: str | Path, lines) -> Path:
    """Write a text file from an iterable of lines, newline-terminated."""
    body = "".join(f"{line}\n" for line in lines)
    return write(root, relative, body)
