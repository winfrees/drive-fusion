"""Keep an "Abbreviations Used in this Document" appendix in every document.

Each Markdown document in the repository ends with a generated appendix: one
table of the abbreviations its prose uses, and, where it cites them, one of the
identifier schemes (requirement IDs, lint rules and so on). The definitions
live here, once, in GLOSSARY and IDENTIFIERS, so a term means the same thing in
every document.

    python tools/doc_abbreviations.py           # check; exit 1 if anything is undefined or stale
    python tools/doc_abbreviations.py --write   # rewrite each document's appendix

What counts as an abbreviation: a word of prose (not code, links or HTML) with
two or more capital letters, such as USN, exFAT, NVMe or SHA-256, and V&V.
Words in IGNORE are not abbreviations: emphasis (NOT), verdicts (PASS),
placeholders (PATH), file names (ROADMAP), and product names that happen to be
in capitals. A new abbreviation in any document fails the check until it is
added to GLOSSARY or IGNORE. tests/test_doc_abbreviations.py runs the check.
"""

