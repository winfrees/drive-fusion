_CODE_FENCE = re.compile(r"^(`{3,}|~{3,}).*?^\1", re.S | re.M)
_INLINE_CODE = re.compile(r"``.*?``|`[^`\n]*`")
_LINK_TARGET = re.compile(r"\]\([^)]*\)")
_URL = re.compile(r"https?://\S+")
_HTML = re.compile(r"<!--.*?-->|<[^>\n]+>", re.S)
_WORD = re.compile(r"[A-Za-z0-9&]+(?:[-‑][A-Za-z0-9&]+)*")
_HEX = re.compile(r"^[0-9A-F]{16,}$")   # key fingerprints and digests


def documents() -> list[Path]:
    out = subprocess.run(["git", "ls-files", "*.md"], cwd=ROOT, capture_output=True, text=True,
                         check=True).stdout.split()
    return [ROOT / p for p in out]


def _strip_appendix(text: str) -> str:
    i = text.find(START)
    return text if i < 0 else text[:i].rstrip() + "\n"


def prose(text: str) -> str:
    text = _strip_appendix(text)
    for pattern in (_CODE_FENCE, _INLINE_CODE, _LINK_TARGET, _URL, _HTML):
        text = pattern.sub(" ", text)
    return "\n\n".join(p for p in re.split(r"\n\s*\n", text) if not _shouted(p))


def _shouted(paragraph: str) -> bool:
    """A paragraph written in capitals, such as a warranty disclaimer ("PROVIDED AS IS,
    WITHOUT WARRANTY OF ANY KIND"): its words are emphasis, not abbreviations."""
    letters = [c for c in paragraph if c.isalpha()]
    return len(letters) >= 40 and sum(c.isupper() for c in letters) >= 0.8 * len(letters)


def _capitals(word: str) -> int:
    return sum(c.isupper() for c in word)


def _lookup(word: str) -> str | None:
    """The glossary key for a word, allowing a plural s."""
    for candidate in (word, word[:-1] if word.endswith("s") else None):
        if candidate and candidate in GLOSSARY:
            return candidate
    return None


def scan(text: str, doc: str = "") -> tuple[set[str], set[int], set[str]]:
    """(abbreviations used, identifier schemes used, undefined words) in a document's prose.

    Schemes are indexes into schemes(doc): IDENTIFIERS, then the LOCAL_IDENTIFIERS for doc.
    """
    return scan_prose(prose(text), doc)


def schemes_for(doc: str) -> list[tuple[str, str, str]]:
    return IDENTIFIERS + [(p, label, meaning) for p, label, meaning, docs in LOCAL_IDENTIFIERS
                          if doc in docs]


def scan_prose(text: str, doc: str = "") -> tuple[set[str], set[int], set[str]]:
    patterns = [re.compile(rf"^{p}$") for p, _, _ in schemes_for(doc)]
    used: set[str] = set()
    schemes: set[int] = set()
    unknown: set[str] = set()
    for match in _WORD.finditer(text):
        word = match.group(0).replace("‑", "-")
        matched = {i for i, rx in enumerate(patterns) if rx.match(word)}
        if matched:
            schemes |= matched
            continue
        if word in IGNORE or _HEX.match(word):
            continue
        key = _lookup(word)
        if key:
            used.add(key)
            continue
        # A compound (SHA-256s, UAC-prompted, NTFS/exFAT): judge each part.
        for part in word.split("-"):
            if part in IGNORE or (_capitals(part) < 2 and part != "V&V"):
                continue
            key = _lookup(part)
            if key:
                used.add(key)
            elif not part.isdigit():
                unknown.add(part)
    return used, schemes, unknown


def _closure(used: set[str], schemes: set[int], doc: str) -> set[str]:
    """Add the abbreviations the definitions themselves use, so the table stands alone."""
    used = set(used)
    texts = [schemes_for(doc)[i][2] for i in schemes] + [GLOSSARY[k] for k in used]
    while texts:
        found, _, _ = scan_prose(" ".join(texts))
        texts = [GLOSSARY[k] for k in found - used]
        used |= found
    return used


def appendix(used: set[str], schemes: set[int], doc: str = "") -> str:
    table = schemes_for(doc)
    used = _closure(used, schemes, doc)
    if not used and not schemes:
        return ""
    lines = [START, "", f"## {TITLE}", ""]
    if used:
        lines += ["| Abbreviation | Meaning |", "|---|---|"]
        lines += [f"| {k} | {GLOSSARY[k]} |" for k in sorted(used, key=lambda k: (k.lower(), k))]
        lines.append("")
    if schemes:
        lines += ["| Identifier | Meaning |", "|---|---|"]
        lines += [f"| {table[i][1]} | {table[i][2]} |" for i in sorted(schemes)]
        lines.append("")
    lines.append(END)
    return "\n".join(lines) + "\n"


def render(text: str, doc: str = "") -> str:
    used, schemes, _ = scan(text, doc)
    body = _strip_appendix(text)
    block = appendix(used, schemes, doc)
    return body + ("\n" + block if block else "")


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--write", action="store_true", help="rewrite each document's appendix")
    args = parser.parse_args(argv)
    problems = []
    for path in documents():
        text = path.read_text(encoding="utf-8")
        rel = path.relative_to(ROOT).as_posix()
        _, _, unknown = scan(text, rel)
        for word in sorted(unknown):
            problems.append(f"{rel}: '{word}' is not defined; add it to GLOSSARY (or IGNORE) "
                            "in tools/doc_abbreviations.py")
        wanted = render(text, rel)
        if wanted != text:
            if args.write:
                path.write_text(wanted, encoding="utf-8", newline="\n")
                print(f"updated {rel}")
            else:
                problems.append(f"{rel}: the abbreviations appendix is missing or stale; run "
                                "python tools/doc_abbreviations.py --write")
    for p in problems:
        print(p, file=sys.stderr)
    if not problems:
        print(f"doc_abbreviations: clean ({len(documents())} documents)")
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
